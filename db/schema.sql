-- Nigerian Sustainable Banking Principles rating platform — Postgres schema.
-- Ported from the SQLite/D1 handoff. Identity credentials live in Neon Auth
-- (neon_auth schema); this schema holds platform profiles and rating data.

CREATE TABLE IF NOT EXISTS users (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  auth_user_id text UNIQUE,
  username text NOT NULL,
  email text NOT NULL,
  role text NOT NULL DEFAULT 'analyst' CHECK (role IN ('admin', 'analyst', 'viewer')),
  profile_role text NOT NULL DEFAULT 'analyst' CHECK (profile_role IN ('admin', 'analyst', 'reviewer', 'partner')),
  first_name text NOT NULL,
  last_name text NOT NULL,
  gender text NOT NULL DEFAULT 'Prefer not to say',
  job_title text NOT NULL DEFAULT '',
  department text NOT NULL DEFAULT '',
  phone text NOT NULL DEFAULT '',
  timezone text NOT NULL DEFAULT 'Africa/Lagos',
  theme_mode text NOT NULL DEFAULT 'dark',
  color_theme text NOT NULL DEFAULT 'amber',
  compact_mode boolean NOT NULL DEFAULT true,
  email_notifications boolean NOT NULL DEFAULT true,
  active boolean NOT NULL DEFAULT true,
  manually_locked boolean NOT NULL DEFAULT false,
  lock_reason text NOT NULL DEFAULT '',
  retired boolean NOT NULL DEFAULT false,
  photo_data_url text NOT NULL DEFAULT '',
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
ALTER TABLE users ADD COLUMN IF NOT EXISTS photo_data_url text NOT NULL DEFAULT '';
CREATE UNIQUE INDEX IF NOT EXISTS idx_users_username_lower ON users (lower(username));
CREATE UNIQUE INDEX IF NOT EXISTS idx_users_email_lower ON users (lower(email));

CREATE TABLE IF NOT EXISTS cbn_categories (
  code text PRIMARY KEY,
  official_name text NOT NULL,
  parent_code text REFERENCES cbn_categories(code) ON DELETE SET NULL,
  description text NOT NULL DEFAULT '',
  source_url text NOT NULL DEFAULT '',
  as_of_date date NOT NULL DEFAULT '2026-07-31',
  sort_order integer NOT NULL DEFAULT 0,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS idx_cbn_categories_name_lower ON cbn_categories (lower(official_name));

CREATE TABLE IF NOT EXISTS institutions (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL,
  type text NOT NULL,
  reporting_period text NOT NULL DEFAULT 'Baseline',
  created_by integer REFERENCES users(id) ON DELETE SET NULL,
  cbn_institution_id integer,
  licence_number text NOT NULL DEFAULT '',
  licence_status text NOT NULL DEFAULT '',
  regulatory_source_url text NOT NULL DEFAULT '',
  regulatory_as_of_date text NOT NULL DEFAULT '',
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS idx_institutions_name_lower ON institutions (lower(name));

CREATE TABLE IF NOT EXISTS signals (
  signal_id text PRIMARY KEY,
  pillar text NOT NULL,
  name text NOT NULL,
  weight double precision NOT NULL CHECK (weight >= 0),
  definition text NOT NULL DEFAULT '',
  measurement text NOT NULL DEFAULT '',
  evidence_required text NOT NULL DEFAULT '',
  score_guide text NOT NULL DEFAULT '',
  primary_framework text NOT NULL DEFAULT '',
  source_url text NOT NULL DEFAULT '',
  notes text NOT NULL DEFAULT '',
  justification text NOT NULL DEFAULT '',
  references_json jsonb NOT NULL DEFAULT '[]'::jsonb,
  methodology_version text NOT NULL DEFAULT ''
);

CREATE TABLE IF NOT EXISTS assessments (
  institution_id integer NOT NULL REFERENCES institutions(id) ON DELETE CASCADE,
  signal_id text NOT NULL REFERENCES signals(signal_id) ON DELETE CASCADE,
  score double precision NOT NULL DEFAULT 0 CHECK (score >= 0 AND score <= 5),
  assessed boolean NOT NULL DEFAULT false,
  evidence_grade double precision NOT NULL DEFAULT 0 CHECK (evidence_grade >= 0 AND evidence_grade <= 3),
  applicable boolean NOT NULL DEFAULT true,
  na_reason text NOT NULL DEFAULT '',
  updated_by integer REFERENCES users(id) ON DELETE SET NULL,
  updated_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (institution_id, signal_id)
);

CREATE TABLE IF NOT EXISTS institution_reviews (
  institution_id integer PRIMARY KEY REFERENCES institutions(id) ON DELETE CASCADE,
  status text NOT NULL DEFAULT 'draft' CHECK (status IN ('draft', 'submitted', 'approved', 'changes_requested')),
  submitted_by integer REFERENCES users(id) ON DELETE SET NULL,
  submitted_at timestamptz,
  reviewed_by integer REFERENCES users(id) ON DELETE SET NULL,
  reviewed_at timestamptz,
  submission_note text NOT NULL DEFAULT '',
  review_note text NOT NULL DEFAULT '',
  cycle_number integer NOT NULL DEFAULT 1 CHECK (cycle_number >= 1),
  revision integer NOT NULL DEFAULT 0 CHECK (revision >= 0),
  methodology_version text NOT NULL DEFAULT '',
  approved_snapshot_id integer,
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS evidence (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  institution_id integer NOT NULL REFERENCES institutions(id) ON DELETE CASCADE,
  signal_id text NOT NULL REFERENCES signals(signal_id) ON DELETE CASCADE,
  reporting_period text NOT NULL DEFAULT 'Baseline',
  evidence_grade double precision NOT NULL DEFAULT 0 CHECK (evidence_grade >= 0 AND evidence_grade <= 3),
  summary text NOT NULL DEFAULT '',
  primary_source_url text NOT NULL DEFAULT '',
  secondary_source_url text NOT NULL DEFAULT '',
  assessment_note text NOT NULL DEFAULT '',
  created_by integer REFERENCES users(id) ON DELETE SET NULL,
  cycle_number integer NOT NULL DEFAULT 1 CHECK (cycle_number >= 1),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS evidence_attachments (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  evidence_id integer NOT NULL REFERENCES evidence(id) ON DELETE CASCADE,
  original_name text NOT NULL,
  stored_name text NOT NULL,
  storage_path text NOT NULL UNIQUE,
  mime_type text NOT NULL DEFAULT 'application/octet-stream',
  size_bytes integer NOT NULL CHECK (size_bytes >= 0),
  sha256 text NOT NULL,
  created_by integer REFERENCES users(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS evidence_blobs (
  storage_path text PRIMARY KEY REFERENCES evidence_attachments(storage_path) ON DELETE CASCADE,
  content bytea NOT NULL
);

CREATE TABLE IF NOT EXISTS audit_log (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id integer REFERENCES users(id) ON DELETE SET NULL,
  action text NOT NULL,
  entity_type text NOT NULL,
  entity_id text NOT NULL,
  details_json jsonb NOT NULL DEFAULT '{}'::jsonb,
  actor_username text NOT NULL DEFAULT '',
  actor_name text NOT NULL DEFAULT '',
  actor_role text NOT NULL DEFAULT '',
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_audit_created_at ON audit_log (created_at DESC);

CREATE TABLE IF NOT EXISTS cbn_institutions (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  official_name text NOT NULL,
  category_code text NOT NULL REFERENCES cbn_categories(code),
  licence_number text NOT NULL DEFAULT '',
  licence_status text NOT NULL DEFAULT 'Licensed',
  state text NOT NULL DEFAULT '',
  address text NOT NULL DEFAULT '',
  website text NOT NULL DEFAULT '',
  source_url text NOT NULL DEFAULT '',
  source_record_id text NOT NULL DEFAULT '',
  as_of_date date NOT NULL DEFAULT '2026-07-31',
  data_json jsonb NOT NULL DEFAULT '{}'::jsonb,
  portfolio_institution_id integer REFERENCES institutions(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_cbn_institutions_category ON cbn_institutions (category_code, official_name);
CREATE INDEX IF NOT EXISTS idx_cbn_institutions_status ON cbn_institutions (licence_status);
CREATE UNIQUE INDEX IF NOT EXISTS idx_cbn_institutions_name_category
  ON cbn_institutions (lower(official_name), category_code);

CREATE TABLE IF NOT EXISTS assessment_snapshots (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  institution_id integer NOT NULL REFERENCES institutions(id) ON DELETE RESTRICT,
  cycle_number integer NOT NULL CHECK (cycle_number >= 1),
  event_type text NOT NULL,
  workflow_status text NOT NULL,
  reporting_period text NOT NULL,
  methodology_version text NOT NULL DEFAULT '',
  revision integer NOT NULL CHECK (revision >= 0),
  snapshot_json jsonb NOT NULL,
  snapshot_hash text NOT NULL UNIQUE,
  created_by integer REFERENCES users(id) ON DELETE SET NULL,
  actor_username text NOT NULL DEFAULT '',
  actor_name text NOT NULL DEFAULT '',
  actor_role text NOT NULL DEFAULT '',
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_snapshots_institution ON assessment_snapshots (institution_id, cycle_number, id DESC);

CREATE TABLE IF NOT EXISTS workflow_events (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  institution_id integer NOT NULL REFERENCES institutions(id) ON DELETE RESTRICT,
  cycle_number integer NOT NULL CHECK (cycle_number >= 1),
  revision integer NOT NULL CHECK (revision >= 0),
  action text NOT NULL,
  from_status text NOT NULL DEFAULT '',
  to_status text NOT NULL DEFAULT '',
  note text NOT NULL DEFAULT '',
  snapshot_id integer REFERENCES assessment_snapshots(id) ON DELETE RESTRICT,
  actor_id integer REFERENCES users(id) ON DELETE SET NULL,
  actor_username text NOT NULL DEFAULT '',
  actor_name text NOT NULL DEFAULT '',
  actor_role text NOT NULL DEFAULT '',
  details_json jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_workflow_events_institution ON workflow_events (institution_id, cycle_number, id DESC);

CREATE TABLE IF NOT EXISTS rating_certificates (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  certificate_number text NOT NULL UNIQUE,
  institution_id integer NOT NULL REFERENCES institutions(id) ON DELETE CASCADE,
  reporting_period text NOT NULL,
  adjusted_score double precision NOT NULL,
  raw_score double precision NOT NULL,
  evidence_confidence double precision NOT NULL,
  rating text NOT NULL,
  methodology_version text NOT NULL DEFAULT '',
  issued_by integer REFERENCES users(id) ON DELETE SET NULL,
  issue_note text NOT NULL DEFAULT '',
  verification_token text NOT NULL UNIQUE,
  issued_at timestamptz NOT NULL DEFAULT now(),
  valid_until timestamptz NOT NULL,
  status text NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'revoked')),
  revoked_by integer REFERENCES users(id) ON DELETE SET NULL,
  revoked_at timestamptz,
  revocation_reason text NOT NULL DEFAULT '',
  institution_name text NOT NULL DEFAULT '',
  institution_type text NOT NULL DEFAULT '',
  issuer_name text NOT NULL DEFAULT '',
  issuer_username text NOT NULL DEFAULT '',
  issuer_role text NOT NULL DEFAULT '',
  approved_snapshot_id integer,
  approved_snapshot_hash text NOT NULL DEFAULT '',
  lifecycle_status text NOT NULL DEFAULT 'active' CHECK (lifecycle_status IN ('active', 'revoked', 'expired', 'superseded')),
  lifecycle_updated_at timestamptz,
  superseded_by integer
);
CREATE INDEX IF NOT EXISTS idx_certificates_institution ON rating_certificates (institution_id, issued_at DESC);
CREATE UNIQUE INDEX IF NOT EXISTS idx_active_certificate_institution ON rating_certificates (institution_id) WHERE status = 'active';

CREATE TABLE IF NOT EXISTS institution_enrollment_requests (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cbn_institution_id integer REFERENCES cbn_institutions(id) ON DELETE SET NULL,
  proposed_name text NOT NULL,
  proposed_type text NOT NULL,
  reporting_period text NOT NULL DEFAULT 'Baseline',
  status text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'approved', 'declined')),
  submitted_by integer REFERENCES users(id) ON DELETE SET NULL,
  submission_comment text NOT NULL,
  submitted_at timestamptz NOT NULL DEFAULT now(),
  reviewed_by integer REFERENCES users(id) ON DELETE SET NULL,
  review_comment text NOT NULL DEFAULT '',
  reviewed_at timestamptz,
  portfolio_institution_id integer REFERENCES institutions(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_enrollment_requests_status ON institution_enrollment_requests (status, submitted_at DESC);
CREATE UNIQUE INDEX IF NOT EXISTS idx_pending_enrollment_cbn
  ON institution_enrollment_requests (cbn_institution_id) WHERE status = 'pending' AND cbn_institution_id IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS idx_pending_enrollment_name
  ON institution_enrollment_requests (lower(proposed_name)) WHERE status = 'pending';

CREATE TABLE IF NOT EXISTS app_metadata (
  key text PRIMARY KEY,
  value text NOT NULL
);

-- Immutability guards: snapshots and workflow events are append-only.
CREATE OR REPLACE FUNCTION reject_mutation() RETURNS trigger AS $$
BEGIN
  RAISE EXCEPTION '% are immutable', TG_TABLE_NAME;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS assessment_snapshots_no_update ON assessment_snapshots;
CREATE TRIGGER assessment_snapshots_no_update BEFORE UPDATE ON assessment_snapshots
  FOR EACH ROW EXECUTE FUNCTION reject_mutation();
DROP TRIGGER IF EXISTS assessment_snapshots_no_delete ON assessment_snapshots;
CREATE TRIGGER assessment_snapshots_no_delete BEFORE DELETE ON assessment_snapshots
  FOR EACH ROW EXECUTE FUNCTION reject_mutation();
DROP TRIGGER IF EXISTS workflow_events_no_update ON workflow_events;
CREATE TRIGGER workflow_events_no_update BEFORE UPDATE ON workflow_events
  FOR EACH ROW EXECUTE FUNCTION reject_mutation();
DROP TRIGGER IF EXISTS workflow_events_no_delete ON workflow_events;
CREATE TRIGGER workflow_events_no_delete BEFORE DELETE ON workflow_events
  FOR EACH ROW EXECUTE FUNCTION reject_mutation();
